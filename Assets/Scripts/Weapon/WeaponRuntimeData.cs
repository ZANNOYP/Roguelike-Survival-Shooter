/// <summary>
/// 武器运行时数据
/// </summary>
public class WeaponRuntimeData
{
    public float damage;// 伤害
    public int bulletCount;// 子弹数量
    public float atkRange;// 攻击范围
    public float spreadAngle;// 散射角度
    public float generateInterval;// 发射间隔
    public float moveSpeed;// 移动速度
    public float deadTime;// 子弹存在时间
    public float rotateSpeed;// 旋转速度
    public float radius;// 旋转半径
}
